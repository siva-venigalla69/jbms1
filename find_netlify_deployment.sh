# Check if Netlify CLI is installed
if command -v netlify &> /dev/null; then
    echo "✅ Netlify CLI is installed"
    echo ""
    echo "Checking login status..."
    netlify status
else
    echo "❌ Netlify CLI is not installed"
    echo ""
