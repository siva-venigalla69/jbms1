import React, { useState, useEffect } from 'react';
import {
  Box,
  Card,
  CardContent,
  Typography,
  Button,
  TextField,
  FormControl,
  InputLabel,
  Select,
  MenuItem,
  Alert,
  CircularProgress,
  Grid,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  Chip,
  Dialog,
  DialogTitle,
  DialogContent,
  DialogActions,
  IconButton,
  Paper,
  Divider,
} from '@mui/material';
import {
  Add,
  Refresh,
  ShoppingCart,
  Visibility,
  Close,
  Delete,
  Send,
  Edit,
} from '@mui/icons-material';
import { simplifiedApi, Customer, Order, OrderItem } from '../services/simplifiedApi';

interface PendingItem {
  material_type: string;
  quantity: number;
  unit_price?: number;
  notes?: string;
}

const OrdersSimplified: React.FC = () => {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [success, setSuccess] = useState<string | null>(null);

  const [customers, setCustomers] = useState<Customer[]>([]);
  const [orders, setOrders] = useState<Order[]>([]);
  const [materialTypes, setMaterialTypes] = useState<string[]>([]);

  // Form state for new order
  const [selectedCustomerId, setSelectedCustomerId] = useState<string>('');
  const [ownershipType, setOwnershipType] = useState<'customer_material' | 'own_stock'>('customer_material');
  const [orderDate, setOrderDate] = useState<string>(new Date().toISOString().split('T')[0]);
  const [expectedDeliveryDate, setExpectedDeliveryDate] = useState<string>('');
  const [orderNotes, setOrderNotes] = useState('');

  // Item form state
  const [materialType, setMaterialType] = useState<string>('');
  const [quantity, setQuantity] = useState<number>(0);
  const [unitPrice, setUnitPrice] = useState<number>(0);
  const [itemNotes, setItemNotes] = useState('');

  // Pending items for new order
  const [pendingItems, setPendingItems] = useState<PendingItem[]>([]);

  // Dialog state for viewing order
  const [viewDialogOpen, setViewDialogOpen] = useState(false);
  const [selectedOrder, setSelectedOrder] = useState<Order | null>(null);
  const [selectedOrderItems, setSelectedOrderItems] = useState<OrderItem[]>([]);

  // Dialog state for adding items to existing order
  const [addItemsDialogOpen, setAddItemsDialogOpen] = useState(false);
  const [addItemsOrder, setAddItemsOrder] = useState<Order | null>(null);
  const [addItemsPending, setAddItemsPending] = useState<PendingItem[]>([]);

  useEffect(() => {
    loadInitialData();
  }, []);

  const loadInitialData = async () => {
    try {
      setLoading(true);
      const [customerData, orderData, materialTypesData] = await Promise.all([
        simplifiedApi.customers.getAll(),
        simplifiedApi.orders.getAll(),
        simplifiedApi.materialTypes.getAll(),
      ]);

      setCustomers(customerData);
      setOrders(orderData);
      setMaterialTypes(materialTypesData.map(t => t.type_code));
    } catch (err: any) {
      setError('Failed to load data: ' + err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleAddItemToBatch = (e: React.FormEvent) => {
    e.preventDefault();

    if (!materialType || quantity <= 0) {
      setError('Please fill in material type and quantity');
      return;
    }

    const newItem: PendingItem = {
      material_type: materialType,
      quantity,
      unit_price: unitPrice > 0 ? unitPrice : undefined,
      notes: itemNotes || undefined,
    };

    setPendingItems([...pendingItems, newItem]);
    setSuccess(`Added ${quantity} ${materialType} to order`);

    // Reset item fields
    setMaterialType('');
    setQuantity(0);
    setUnitPrice(0);
    setItemNotes('');
  };

  const handleRemoveItem = (index: number) => {
    const newItems = [...pendingItems];
    newItems.splice(index, 1);
    setPendingItems(newItems);
  };

  const handleSubmitOrder = async () => {
    if (pendingItems.length === 0) {
      setError('Please add at least one item to the order');
      return;
    }

    if (ownershipType === 'customer_material' && !selectedCustomerId) {
      setError('Please select a customer for customer material orders');
      return;
    }

    try {
      setLoading(true);

      // Create order first
      const orderData = {
        customer_id: ownershipType === 'customer_material' ? selectedCustomerId : null,
        order_number: '', // Auto-generated by database
        ownership_type: ownershipType,
        total_quantity: 0, // Will be auto-calculated by trigger
        status: 'active',
        order_date: orderDate,
        expected_delivery_date: expectedDeliveryDate || undefined,
        notes: orderNotes,
      };

      const createdOrder = await simplifiedApi.orders.create(orderData);

      // Create all order items
      const items = pendingItems.map(item => ({
        order_id: createdOrder.id,
        material_type: item.material_type,
        quantity: item.quantity,
        unit_price: item.unit_price,
        notes: item.notes,
      }));

      await simplifiedApi.orderItems.createMultiple(items);

      const totalQuantity = pendingItems.reduce((sum, item) => sum + item.quantity, 0);
      setSuccess(`Order ${createdOrder.order_number} created successfully! ${pendingItems.length} items, ${totalQuantity} total quantity.`);

      // Reset form
      setSelectedCustomerId('');
      setOwnershipType('customer_material');
      setOrderDate(new Date().toISOString().split('T')[0]);
      setExpectedDeliveryDate('');
      setOrderNotes('');
      setPendingItems([]);

      // Reload orders
      const orderData2 = await simplifiedApi.orders.getAll();
      setOrders(orderData2);
    } catch (err: any) {
      setError('Failed to create order: ' + err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleViewOrder = async (order: Order) => {
    try {
      setLoading(true);
      const items = await simplifiedApi.orderItems.getByOrder(order.id);
      setSelectedOrder(order);
      setSelectedOrderItems(items);
      setViewDialogOpen(true);
    } catch (err: any) {
      setError('Failed to load order items: ' + err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleOpenAddItemsDialog = async (order: Order) => {
    try {
      setLoading(true);
      setAddItemsOrder(order);
      setAddItemsPending([]);
      setAddItemsDialogOpen(true);
    } catch (err: any) {
      setError('Failed to open add items dialog: ' + err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleAddItemToExisting = (e: React.FormEvent) => {
    e.preventDefault();

    if (!materialType || quantity <= 0) {
      setError('Please fill in material type and quantity');
      return;
    }

    const newItem: PendingItem = {
      material_type: materialType,
      quantity,
      unit_price: unitPrice > 0 ? unitPrice : undefined,
      notes: itemNotes || undefined,
    };

    setAddItemsPending([...addItemsPending, newItem]);
    setSuccess(`Added ${quantity} ${materialType} to order`);

    // Reset item fields
    setMaterialType('');
    setQuantity(0);
    setUnitPrice(0);
    setItemNotes('');
  };

  const handleRemoveAddItem = (index: number) => {
    const newItems = [...addItemsPending];
    newItems.splice(index, 1);
    setAddItemsPending(newItems);
  };

  const handleSubmitAddItems = async () => {
    if (addItemsPending.length === 0 || !addItemsOrder) {
      setError('No items to add');
      return;
    }

    try {
      setLoading(true);

      const items = addItemsPending.map(item => ({
        order_id: addItemsOrder.id,
        material_type: item.material_type,
        quantity: item.quantity,
        unit_price: item.unit_price,
        notes: item.notes,
      }));

      await simplifiedApi.orderItems.createMultiple(items);

      const totalQuantity = addItemsPending.reduce((sum, item) => sum + item.quantity, 0);
      setSuccess(`Added ${addItemsPending.length} items (${totalQuantity} quantity) to order ${addItemsOrder.order_number}!`);

      setAddItemsDialogOpen(false);
      setAddItemsPending([]);
      setAddItemsOrder(null);

      // Reload orders
      const orderData = await simplifiedApi.orders.getAll();
      setOrders(orderData);
    } catch (err: any) {
      setError('Failed to add items: ' + err.message);
    } finally {
      setLoading(false);
    }
  };

  const getCustomerName = (customerId: string | null) => {
    if (!customerId) return 'Own Stock';
    const customer = customers.find(c => c.id === customerId);
    return customer?.name || 'Unknown Customer';
  };

  const getStatusColor = (status: string) => {
    switch (status?.toLowerCase()) {
      case 'active':
        return 'success';
      case 'completed':
        return 'primary';
      case 'cancelled':
        return 'error';
      default:
        return 'default';
    }
  };

  const getTotalPendingQuantity = () => {
    return pendingItems.reduce((sum, item) => sum + item.quantity, 0);
  };

  const getAddItemsTotalQuantity = () => {
    return addItemsPending.reduce((sum, item) => sum + item.quantity, 0);
  };

  return (
    <Box>
      <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', mb: 3 }}>
        <Typography variant="h4" fontWeight="bold">
          Orders
        </Typography>
        <Button variant="outlined" startIcon={<Refresh />} onClick={loadInitialData} disabled={loading}>
          Refresh
        </Button>
      </Box>

      {error && (
        <Alert severity="error" sx={{ mb: 2 }} onClose={() => setError(null)}>
          {error}
        </Alert>
      )}
      {success && (
        <Alert severity="success" sx={{ mb: 2 }} onClose={() => setSuccess(null)}>
          {success}
        </Alert>
      )}

      <Grid container spacing={3}>
        <Grid item xs={12} md={5}>
          <Card>
            <CardContent>
              <Box sx={{ display: 'flex', alignItems: 'center', gap: 2, mb: 3 }}>
                <Add color="primary" />
                <Typography variant="h6">Create New Order</Typography>
              </Box>

              <Box sx={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
                {/* Ownership Type */}
                <FormControl fullWidth required>
                  <InputLabel>Ownership Type</InputLabel>
                  <Select
                    value={ownershipType}
                    onChange={(e) => {
                      setOwnershipType(e.target.value as 'customer_material' | 'own_stock');
                      if (e.target.value === 'own_stock') {
                        setSelectedCustomerId('');
                      }
                    }}
                    label="Ownership Type"
                  >
                    <MenuItem value="customer_material">Customer Material (Job Work)</MenuItem>
                    <MenuItem value="own_stock">Own Stock</MenuItem>
                  </Select>
                </FormControl>

                {/* Customer Selection */}
                {ownershipType === 'customer_material' && (
                  <FormControl fullWidth required>
                    <InputLabel>Customer</InputLabel>
                    <Select
                      value={selectedCustomerId}
                      onChange={(e) => setSelectedCustomerId(e.target.value)}
                      label="Customer"
                    >
                      {customers.map(customer => (
                        <MenuItem key={customer.id} value={customer.id}>
                          {customer.name} - {customer.phone}
                        </MenuItem>
                      ))}
                    </Select>
                  </FormControl>
                )}

                <TextField
                  label="Order Date"
                  type="date"
                  value={orderDate}
                  onChange={(e) => setOrderDate(e.target.value)}
                  InputLabelProps={{ shrink: true }}
                  fullWidth
                  required
                />

                <TextField
                  label="Expected Delivery Date"
                  type="date"
                  value={expectedDeliveryDate}
                  onChange={(e) => setExpectedDeliveryDate(e.target.value)}
                  InputLabelProps={{ shrink: true }}
                  fullWidth
                />

                <TextField
                  label="Order Notes"
                  value={orderNotes}
                  onChange={(e) => setOrderNotes(e.target.value)}
                  multiline
                  rows={2}
                  fullWidth
                  placeholder="Order details, special instructions..."
                />

                <Divider sx={{ my: 1 }} />

                <Typography variant="subtitle2" color="primary">
                  Add Items to Order
                </Typography>

                <form onSubmit={handleAddItemToBatch}>
                  <Box sx={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
                    <FormControl fullWidth required>
                      <InputLabel>Material Type</InputLabel>
                      <Select
                        value={materialType}
                        onChange={(e) => setMaterialType(e.target.value)}
                        label="Material Type"
                      >
                        {materialTypes.map(type => (
                          <MenuItem key={type} value={type}>
                            {type?.toUpperCase() || type}
                          </MenuItem>
                        ))}
                      </Select>
                    </FormControl>

                    <TextField
                      label="Quantity"
                      type="number"
                      value={quantity}
                      onChange={(e) => setQuantity(Number(e.target.value))}
                      inputProps={{ min: 1 }}
                      fullWidth
                      required
                    />

                    <TextField
                      label="Unit Price (Optional)"
                      type="number"
                      value={unitPrice}
                      onChange={(e) => setUnitPrice(Number(e.target.value))}
                      inputProps={{ min: 0, step: 0.01 }}
                      fullWidth
                      placeholder="Price per unit"
                    />

                    <TextField
                      label="Item Notes (Optional)"
                      value={itemNotes}
                      onChange={(e) => setItemNotes(e.target.value)}
                      multiline
                      rows={2}
                      fullWidth
                      placeholder="Notes for this specific item..."
                    />

                    <Button
                      type="submit"
                      variant="outlined"
                      fullWidth
                      startIcon={<Add />}
                    >
                      Add Item to Order
                    </Button>
                  </Box>
                </form>

                {/* Pending Items Table */}
                {pendingItems.length > 0 && (
                  <>
                    <Divider sx={{ my: 2 }} />
                    <Box>
                      <Typography variant="subtitle2" color="primary" gutterBottom>
                        Items in This Order ({pendingItems.length} items, {getTotalPendingQuantity()} total)
                      </Typography>
                      <Paper variant="outlined" sx={{ maxHeight: 200, overflow: 'auto', mt: 1 }}>
                        <Table size="small">
                          <TableHead>
                            <TableRow>
                              <TableCell>Material</TableCell>
                              <TableCell align="right">Qty</TableCell>
                              <TableCell align="right">Price</TableCell>
                              <TableCell align="right">Action</TableCell>
                            </TableRow>
                          </TableHead>
                          <TableBody>
                            {pendingItems.map((item, index) => (
                              <TableRow key={index}>
                                <TableCell>
                                  <Typography variant="body2" fontWeight="medium">
                                    {item.material_type?.toUpperCase()}
                                  </Typography>
                                  {item.notes && (
                                    <Typography variant="caption" color="text.secondary">
                                      {item.notes}
                                    </Typography>
                                  )}
                                </TableCell>
                                <TableCell align="right">
                                  <Chip label={item.quantity} color="primary" size="small" />
                                </TableCell>
                                <TableCell align="right">
                                  {item.unit_price ? `₹${item.unit_price}` : '-'}
                                </TableCell>
                                <TableCell align="right">
                                  <IconButton
                                    size="small"
                                    color="error"
                                    onClick={() => handleRemoveItem(index)}
                                  >
                                    <Delete fontSize="small" />
                                  </IconButton>
                                </TableCell>
                              </TableRow>
                            ))}
                          </TableBody>
                        </Table>
                      </Paper>
                    </Box>

                    <Button
                      variant="contained"
                      fullWidth
                      disabled={loading}
                      startIcon={loading ? <CircularProgress size={20} /> : <Send />}
                      onClick={handleSubmitOrder}
                      sx={{ mt: 2 }}
                    >
                      {loading ? 'Creating...' : `Create Order with ${pendingItems.length} Item(s)`}
                    </Button>
                  </>
                )}

                {pendingItems.length === 0 && (
                  <Alert severity="info" sx={{ mt: 2 }}>
                    <Typography variant="body2">
                      Add items to the order before submitting. You can add multiple material types with quantities.
                    </Typography>
                  </Alert>
                )}
              </Box>
            </CardContent>
          </Card>
        </Grid>

        <Grid item xs={12} md={7}>
          <Card>
            <CardContent>
              <Box sx={{ display: 'flex', alignItems: 'center', gap: 2, mb: 3 }}>
                <ShoppingCart color="primary" />
                <Typography variant="h6">All Orders</Typography>
              </Box>

              {loading ? (
                <Box sx={{ display: 'flex', justifyContent: 'center', py: 4 }}>
                  <CircularProgress />
                </Box>
              ) : orders.length === 0 ? (
                <Box sx={{ textAlign: 'center', py: 8 }}>
                  <ShoppingCart sx={{ fontSize: 64, color: 'text.secondary', mb: 2 }} />
                  <Typography variant="h6" color="text.secondary">
                    No orders yet
                  </Typography>
                </Box>
              ) : (
                <TableContainer sx={{ maxHeight: '60vh' }}>
                  <Table stickyHeader size="small">
                    <TableHead>
                      <TableRow>
                        <TableCell>Order Number</TableCell>
                        <TableCell>Customer</TableCell>
                        <TableCell>Quantity</TableCell>
                        <TableCell>Status</TableCell>
                        <TableCell>Order Date</TableCell>
                        <TableCell align="right">Actions</TableCell>
                      </TableRow>
                    </TableHead>
                    <TableBody>
                      {orders.map((order) => (
                        <TableRow key={order.id} hover>
                          <TableCell>
                            <Typography variant="body2" fontWeight="bold">
                              {order.order_number}
                            </Typography>
                          </TableCell>
                          <TableCell>{getCustomerName(order.customer_id)}</TableCell>
                          <TableCell>
                            <Chip label={order.total_quantity} color="primary" size="small" />
                          </TableCell>
                          <TableCell>
                            <Chip
                              label={order.status?.toUpperCase() || 'ACTIVE'}
                              color={getStatusColor(order.status)}
                              size="small"
                            />
                          </TableCell>
                          <TableCell>
                            {new Date(order.order_date).toLocaleDateString()}
                          </TableCell>
                          <TableCell align="right">
                            <IconButton
                              size="small"
                              onClick={() => handleViewOrder(order)}
                              color="primary"
                              title="View Order"
                            >
                              <Visibility fontSize="small" />
                            </IconButton>
                            <IconButton
                              size="small"
                              onClick={() => handleOpenAddItemsDialog(order)}
                              color="secondary"
                              title="Add Items"
                            >
                              <Add fontSize="small" />
                            </IconButton>
                          </TableCell>
                        </TableRow>
                      ))}
                    </TableBody>
                  </Table>
                </TableContainer>
              )}
            </CardContent>
          </Card>
        </Grid>
      </Grid>

      {/* View Order Dialog */}
      <Dialog
        open={viewDialogOpen}
        onClose={() => setViewDialogOpen(false)}
        maxWidth="md"
        fullWidth
      >
        <DialogTitle>
          <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
            <Typography variant="h6">Order Details</Typography>
            <IconButton onClick={() => setViewDialogOpen(false)}>
              <Close />
            </IconButton>
          </Box>
        </DialogTitle>
        <DialogContent dividers>
          {selectedOrder && (
            <Box sx={{ display: 'flex', flexDirection: 'column', gap: 3 }}>
              <Grid container spacing={2}>
                <Grid item xs={6}>
                  <Typography variant="caption" color="text.secondary">
                    Order Number
                  </Typography>
                  <Typography variant="body1" fontWeight="bold">
                    {selectedOrder.order_number}
                  </Typography>
                </Grid>

                <Grid item xs={6}>
                  <Typography variant="caption" color="text.secondary">
                    Customer
                  </Typography>
                  <Typography variant="body1">
                    {getCustomerName(selectedOrder.customer_id)}
                  </Typography>
                </Grid>

                <Grid item xs={6}>
                  <Typography variant="caption" color="text.secondary">
                    Ownership Type
                  </Typography>
                  <Chip
                    label={selectedOrder.ownership_type?.replace('_', ' ').toUpperCase() || 'N/A'}
                    size="small"
                    sx={{ mt: 0.5 }}
                  />
                </Grid>

                <Grid item xs={6}>
                  <Typography variant="caption" color="text.secondary">
                    Total Quantity
                  </Typography>
                  <Typography variant="h5" fontWeight="bold" color="primary.main">
                    {selectedOrder.total_quantity}
                  </Typography>
                </Grid>

                <Grid item xs={6}>
                  <Typography variant="caption" color="text.secondary">
                    Status
                  </Typography>
                  <Chip
                    label={selectedOrder.status?.toUpperCase() || 'ACTIVE'}
                    color={getStatusColor(selectedOrder.status)}
                    size="small"
                    sx={{ mt: 0.5 }}
                  />
                </Grid>

                <Grid item xs={6}>
                  <Typography variant="caption" color="text.secondary">
                    Order Date
                  </Typography>
                  <Typography variant="body1">
                    {new Date(selectedOrder.order_date).toLocaleDateString()}
                  </Typography>
                </Grid>

                {selectedOrder.expected_delivery_date && (
                  <Grid item xs={12}>
                    <Typography variant="caption" color="text.secondary">
                      Expected Delivery Date
                    </Typography>
                    <Typography variant="body1">
                      {new Date(selectedOrder.expected_delivery_date).toLocaleDateString()}
                    </Typography>
                  </Grid>
                )}

                {selectedOrder.notes && (
                  <Grid item xs={12}>
                    <Typography variant="caption" color="text.secondary">
                      Order Notes
                    </Typography>
                    <Typography variant="body1">
                      {selectedOrder.notes}
                    </Typography>
                  </Grid>
                )}
              </Grid>

              <Divider />

              <Box>
                <Typography variant="subtitle1" fontWeight="bold" gutterBottom>
                  Order Items ({selectedOrderItems.length})
                </Typography>
                {selectedOrderItems.length > 0 ? (
                  <TableContainer component={Paper} variant="outlined">
                    <Table size="small">
                      <TableHead>
                        <TableRow>
                          <TableCell>Material Type</TableCell>
                          <TableCell align="right">Quantity</TableCell>
                          <TableCell align="right">Unit Price</TableCell>
                          <TableCell>Notes</TableCell>
                        </TableRow>
                      </TableHead>
                      <TableBody>
                        {selectedOrderItems.map((item) => (
                          <TableRow key={item.id}>
                            <TableCell>
                              <Typography variant="body2" fontWeight="medium">
                                {item.material_type?.toUpperCase()}
                              </Typography>
                            </TableCell>
                            <TableCell align="right">
                              <Chip label={item.quantity} color="primary" size="small" />
                            </TableCell>
                            <TableCell align="right">
                              {item.unit_price ? `₹${item.unit_price?.toFixed(2)}` : '-'}
                            </TableCell>
                            <TableCell>
                              <Typography variant="caption" color="text.secondary">
                                {item.notes || '-'}
                              </Typography>
                            </TableCell>
                          </TableRow>
                        ))}
                      </TableBody>
                    </Table>
                  </TableContainer>
                ) : (
                  <Alert severity="info">No items in this order yet</Alert>
                )}
              </Box>
            </Box>
          )}
        </DialogContent>
        <DialogActions>
          <Button onClick={() => setViewDialogOpen(false)}>Close</Button>
        </DialogActions>
      </Dialog>

      {/* Add Items to Existing Order Dialog */}
      <Dialog
        open={addItemsDialogOpen}
        onClose={() => setAddItemsDialogOpen(false)}
        maxWidth="sm"
        fullWidth
      >
        <DialogTitle>
          <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
            <Typography variant="h6">
              Add Items to Order {addItemsOrder?.order_number}
            </Typography>
            <IconButton onClick={() => setAddItemsDialogOpen(false)}>
              <Close />
            </IconButton>
          </Box>
        </DialogTitle>
        <DialogContent dividers>
          <Box sx={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
            <Alert severity="info">
              Add more items to this existing order. The total quantity will be automatically updated.
            </Alert>

            <form onSubmit={handleAddItemToExisting}>
              <Box sx={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
                <FormControl fullWidth required>
                  <InputLabel>Material Type</InputLabel>
                  <Select
                    value={materialType}
                    onChange={(e) => setMaterialType(e.target.value)}
                    label="Material Type"
                  >
                    {materialTypes.map(type => (
                      <MenuItem key={type} value={type}>
                        {type?.toUpperCase() || type}
                      </MenuItem>
                    ))}
                  </Select>
                </FormControl>

                <TextField
                  label="Quantity"
                  type="number"
                  value={quantity}
                  onChange={(e) => setQuantity(Number(e.target.value))}
                  inputProps={{ min: 1 }}
                  fullWidth
                  required
                />

                <TextField
                  label="Unit Price (Optional)"
                  type="number"
                  value={unitPrice}
                  onChange={(e) => setUnitPrice(Number(e.target.value))}
                  inputProps={{ min: 0, step: 0.01 }}
                  fullWidth
                />

                <TextField
                  label="Item Notes (Optional)"
                  value={itemNotes}
                  onChange={(e) => setItemNotes(e.target.value)}
                  multiline
                  rows={2}
                  fullWidth
                />

                <Button
                  type="submit"
                  variant="outlined"
                  fullWidth
                  startIcon={<Add />}
                >
                  Add Item
                </Button>
              </Box>
            </form>

            {addItemsPending.length > 0 && (
              <>
                <Divider sx={{ my: 2 }} />
                <Box>
                  <Typography variant="subtitle2" color="primary" gutterBottom>
                    Pending Items ({addItemsPending.length} items, {getAddItemsTotalQuantity()} total)
                  </Typography>
                  <Paper variant="outlined" sx={{ maxHeight: 200, overflow: 'auto', mt: 1 }}>
                    <Table size="small">
                      <TableHead>
                        <TableRow>
                          <TableCell>Material</TableCell>
                          <TableCell align="right">Qty</TableCell>
                          <TableCell align="right">Action</TableCell>
                        </TableRow>
                      </TableHead>
                      <TableBody>
                        {addItemsPending.map((item, index) => (
                          <TableRow key={index}>
                            <TableCell>
                              <Typography variant="body2" fontWeight="medium">
                                {item.material_type?.toUpperCase()}
                              </Typography>
                            </TableCell>
                            <TableCell align="right">
                              <Chip label={item.quantity} color="primary" size="small" />
                            </TableCell>
                            <TableCell align="right">
                              <IconButton
                                size="small"
                                color="error"
                                onClick={() => handleRemoveAddItem(index)}
                              >
                                <Delete fontSize="small" />
                              </IconButton>
                            </TableCell>
                          </TableRow>
                        ))}
                      </TableBody>
                    </Table>
                  </Paper>
                </Box>
              </>
            )}
          </Box>
        </DialogContent>
        <DialogActions>
          <Button onClick={() => setAddItemsDialogOpen(false)}>Cancel</Button>
          <Button
            variant="contained"
            onClick={handleSubmitAddItems}
            disabled={loading || addItemsPending.length === 0}
            startIcon={loading ? <CircularProgress size={20} /> : <Send />}
          >
            {loading ? 'Adding...' : `Add ${addItemsPending.length} Item(s)`}
          </Button>
        </DialogActions>
      </Dialog>
    </Box>
  );
};

export default OrdersSimplified;
